-- PostgreSQL bootstrap schema for fvpAdminBackend
-- Run this after creating the database `agrib2b`.
-- Example:
--   createdb agrib2b
--   psql -d agrib2b -f schema-bootstrap.sql

CREATE SCHEMA IF NOT EXISTS agrib2b;
SET search_path TO agrib2b, public;

CREATE TABLE IF NOT EXISTS category (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL UNIQUE,
    slug VARCHAR(255) NOT NULL UNIQUE,
    description VARCHAR(500) NOT NULL
);

CREATE TABLE IF NOT EXISTS app_role (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(50) NOT NULL UNIQUE,
    name VARCHAR(100) NOT NULL,
    description VARCHAR(255)
);

CREATE TABLE IF NOT EXISTS customer (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR(160) NOT NULL,
    company_name VARCHAR(180) NOT NULL,
    email VARCHAR(255) NOT NULL UNIQUE,
    phone VARCHAR(40) NOT NULL,
    delivery_address VARCHAR(400) NOT NULL,
    city VARCHAR(120) NOT NULL,
    state VARCHAR(120) NOT NULL,
    postal_code VARCHAR(20) NOT NULL,
    password_hash VARCHAR(255),
    auth_provider VARCHAR(30) NOT NULL,
    google_subject VARCHAR(255),
    email_verified BOOLEAN NOT NULL,
    preferred_payment_method VARCHAR(40),
    preferred_payment_handle VARCHAR(120),
    active BOOLEAN NOT NULL,
    deferred_payment_eligible BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL
);

CREATE TABLE IF NOT EXISTS customer_address (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id BIGINT NOT NULL,
    label VARCHAR(60) NOT NULL,
    recipient_name VARCHAR(160) NOT NULL,
    phone VARCHAR(40) NOT NULL,
    line1 VARCHAR(400) NOT NULL,
    line2 VARCHAR(400),
    city VARCHAR(120) NOT NULL,
    state VARCHAR(120) NOT NULL,
    postal_code VARCHAR(20) NOT NULL,
    country VARCHAR(120) NOT NULL,
    is_default BOOLEAN NOT NULL,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_customer_address_customer FOREIGN KEY (customer_id) REFERENCES customer(id)
);

CREATE TABLE IF NOT EXISTS app_document (
    id UUID PRIMARY KEY,
    original_file_name VARCHAR(255) NOT NULL,
    object_key VARCHAR(800) NOT NULL UNIQUE,
    path VARCHAR(800) NOT NULL UNIQUE,
    content_type VARCHAR(120),
    size_bytes BIGINT,
    checksum_sha256 VARCHAR(128),
    module VARCHAR(80) NOT NULL,
    owner_id BIGINT,
    status VARCHAR(20) NOT NULL,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL
);

