    farming_type VARCHAR(80),
    land_area VARCHAR(80),
    main_crops VARCHAR(255),
    irrigation_type VARCHAR(80),
    bank_account_number VARCHAR(40),
    ifsc_code VARCHAR(20),
    village VARCHAR(160),
    district VARCHAR(160),
    farmer_state VARCHAR(120),
    pin_code VARCHAR(20),
    collection_hub_name VARCHAR(160),
    hub_storage_type VARCHAR(80),
    hub_capacity_mt NUMERIC(12, 2),
    hub_pickup_radius_km INTEGER,
    hub_operating_days VARCHAR(120),
    hub_code VARCHAR(40),
    id_proof_url VARCHAR(500),
    id_proof_document_id UUID,
    id_proof_metadata VARCHAR(1200),
    payment_screenshot_url VARCHAR(500),
    payment_screenshot_document_id UUID,
    payment_screenshot_metadata VARCHAR(1200),
    aadhaar_document_url VARCHAR(500),
    aadhaar_document_id UUID,
    aadhaar_document_metadata VARCHAR(1200),
    land_proof_document_url VARCHAR(500),
    land_proof_document_id UUID,
    land_proof_document_metadata VARCHAR(1200),
    bank_passbook_document_url VARCHAR(500),
    bank_passbook_document_id UUID,
    bank_passbook_document_metadata VARCHAR(1200),
    hub_document_url VARCHAR(500),
    hub_document_id UUID,
    hub_document_metadata VARCHAR(1200),
    terms_accepted BOOLEAN,
    agreement_id VARCHAR(40),
    committed_return_amount NUMERIC(14, 2),
    farmer_action_note VARCHAR(1200),
    hub_action_note VARCHAR(1200),
    verification_status VARCHAR(20),
